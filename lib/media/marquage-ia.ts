// Marquage des images générées par IA (AI Act, art. 50 §2) : métadonnées lisibles par machine
// écrites dans le fichier lui-même, sans réencodage (les pixels ne changent pas).
//   JPEG : segment APP1 EXIF (ImageDescription, Software, DateTime) + segment APP1 XMP.
//   PNG  : blocs texte tEXt/iTXt (AI-Generated, Software, Creation Time, Description) + XMP (iTXt).
//   WebP : bloc XMP (chunk « XMP  », drapeau XMP du chunk VP8X).
// Le XMP porte le vocabulaire IPTC « DigitalSourceType = trainedAlgorithmicMedia », celui que
// lisent les outils de vérification. Pas de C2PA (pas de signature).
import { crc32 } from "node:zlib";

export type InfosMarquageIa = {
  /** Nom du fournisseur (« OpenAI »). */
  fournisseur: string;
  /** Modèle utilisé, facultatif (« gpt-image-1 »). */
  modele?: string;
  date: Date;
};

export const MENTION_METADONNEE_IA = "Generated by AI";
export const DIGITAL_SOURCE_TYPE_IA = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia";

const xml = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const outil = (i: InfosMarquageIa) => (i.modele ? `${i.fournisseur} ${i.modele}` : i.fournisseur);

export function paquetXmp(infos: InfosMarquageIa): string {
  return (
    `<?xpacket begin="﻿" id="W5M0MpCehiHzreSzNTczkc9d"?>` +
    `<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">` +
    `<rdf:Description rdf:about="" xmlns:xmp="http://ns.adobe.com/xap/1.0/" xmlns:dc="http://purl.org/dc/elements/1.1/"` +
    ` xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/"` +
    ` Iptc4xmpExt:DigitalSourceType="${DIGITAL_SOURCE_TYPE_IA}"` +
    ` xmp:CreatorTool="${xml(outil(infos))}" xmp:CreateDate="${infos.date.toISOString()}">` +
    `<dc:description><rdf:Alt><rdf:li xml:lang="x-default">${xml(`${MENTION_METADONNEE_IA} (${outil(infos)})`)}</rdf:li></rdf:Alt></dc:description>` +
    `</rdf:Description></rdf:RDF></x:xmpmeta><?xpacket end="r"?>`
  );
}

export type FormatImage = "jpeg" | "png" | "webp";

export function formatImage(octets: Buffer): FormatImage | null {
  if (octets.length >= 3 && octets[0] === 0xff && octets[1] === 0xd8 && octets[2] === 0xff) return "jpeg";
  if (octets.length >= 8 && octets.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return "png";
  if (octets.length >= 12 && octets.toString("latin1", 0, 4) === "RIFF" && octets.toString("latin1", 8, 12) === "WEBP") return "webp";
  return null;
}

/** Ajoute les métadonnées IA à une image JPEG, PNG ou WebP. Lève une erreur pour un autre format
 *  ou un fichier illisible (l'appelant décide quoi faire). */
export function marquerImageIa(octets: Buffer, infos: InfosMarquageIa): Buffer {
  const format = formatImage(octets);
  if (format === "png") return marquerPng(octets, infos);
  if (format === "jpeg") return marquerJpeg(octets, infos);
  if (format === "webp") return marquerWebp(octets, infos);
  throw new Error("Format d'image non pris en charge pour le marquage IA");
}

// ─── PNG ────────────────────────────────────────────────────────────────────────

function blocPng(type: string, donnees: Buffer): Buffer {
  const longueur = Buffer.alloc(4);
  longueur.writeUInt32BE(donnees.length);
  const typeEtDonnees = Buffer.concat([Buffer.from(type, "latin1"), donnees]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(typeEtDonnees) >>> 0);
  return Buffer.concat([longueur, typeEtDonnees, crc]);
}

const tExt = (cle: string, valeur: string) => blocPng("tEXt", Buffer.concat([Buffer.from(cle, "latin1"), Buffer.from([0]), Buffer.from(valeur, "latin1")]));
// iTXt non compressé : mot-clé \0 drapeau(0) méthode(0) langue \0 mot-clé traduit \0 texte UTF-8.
const iTxt = (cle: string, valeur: string) =>
  blocPng("iTXt", Buffer.concat([Buffer.from(cle, "latin1"), Buffer.from([0, 0, 0, 0, 0]), Buffer.from(valeur, "utf8")]));

function marquerPng(octets: Buffer, infos: InfosMarquageIa): Buffer {
  // Blocs texte juste après IHDR (toujours le premier bloc), donc avant les données d'image :
  // certains lecteurs n'examinent pas les blocs placés après IDAT.
  if (octets.length < 33 || octets.toString("latin1", 12, 16) !== "IHDR") throw new Error("PNG sans bloc IHDR");
  const apresIhdr = 8 + 12 + octets.readUInt32BE(8);
  if (apresIhdr > octets.length) throw new Error("PNG tronqué");
  const blocs = Buffer.concat([
    tExt("AI-Generated", "true"),
    tExt("Software", outil(infos)),
    tExt("Creation Time", infos.date.toISOString()),
    iTxt("Description", `${MENTION_METADONNEE_IA} (${outil(infos)})`),
    iTxt("XML:com.adobe.xmp", paquetXmp(infos)),
  ]);
  return Buffer.concat([octets.subarray(0, apresIhdr), blocs, octets.subarray(apresIhdr)]);
}

// ─── JPEG ───────────────────────────────────────────────────────────────────────

function segmentApp1(contenu: Buffer): Buffer {
  const entete = Buffer.from([0xff, 0xe1, 0, 0]);
  entete.writeUInt16BE(contenu.length + 2, 2);
  return Buffer.concat([entete, contenu]);
}

// EXIF minimal : un IFD0 (TIFF little-endian) avec trois champs ASCII.
export function blocExif(infos: InfosMarquageIa): Buffer {
  const d = infos.date;
  const p = (n: number) => String(n).padStart(2, "0");
  const dateExif = `${d.getUTCFullYear()}:${p(d.getUTCMonth() + 1)}:${p(d.getUTCDate())} ${p(d.getUTCHours())}:${p(d.getUTCMinutes())}:${p(d.getUTCSeconds())}`;
  const champs: [number, string][] = [
    [0x010e, `${MENTION_METADONNEE_IA} (${outil(infos)})`], // ImageDescription
    [0x0131, outil(infos)], // Software
    [0x0132, dateExif], // DateTime
  ];
  const debutDonnees = 8 + 2 + champs.length * 12 + 4;
  const ifd = Buffer.alloc(2 + champs.length * 12 + 4);
  ifd.writeUInt16LE(champs.length, 0);
  const donnees: Buffer[] = [];
  let decalage = debutDonnees;
  champs.forEach(([tag, valeur], i) => {
    const ascii = Buffer.from(`${valeur.replace(/[^\x20-\x7e]/g, "?")}\0`, "latin1");
    const o = 2 + i * 12;
    ifd.writeUInt16LE(tag, o);
    ifd.writeUInt16LE(2, o + 2); // ASCII
    ifd.writeUInt32LE(ascii.length, o + 4);
    if (ascii.length <= 4) {
      ascii.copy(ifd, o + 8);
    } else {
      ifd.writeUInt32LE(decalage, o + 8);
      donnees.push(ascii);
      decalage += ascii.length;
    }
  });
  // IFD suivant : aucun (4 octets à zéro déjà présents).
  const tiff = Buffer.concat([Buffer.from([0x49, 0x49, 0x2a, 0x00, 0x08, 0x00, 0x00, 0x00]), ifd, ...donnees]);
  return Buffer.concat([Buffer.from("Exif\0\0", "latin1"), tiff]);
}

function marquerJpeg(octets: Buffer, infos: InfosMarquageIa): Buffer {
  // On parcourt les segments APPn en tête de fichier : EXIF et XMP se placent juste après
  // eux (après APP0 JFIF, comme l'exige JFIF). Un EXIF déjà présent est conservé tel quel.
  let pos = 2;
  let exifPresent = false;
  while (pos + 4 <= octets.length && octets[pos] === 0xff && octets[pos + 1] >= 0xe0 && octets[pos + 1] <= 0xef) {
    const longueur = octets.readUInt16BE(pos + 2);
    if (octets[pos + 1] === 0xe1 && octets.toString("latin1", pos + 4, pos + 10) === "Exif\0\0") exifPresent = true;
    pos += 2 + longueur;
  }
  if (pos > octets.length) throw new Error("JPEG tronqué");
  const xmp = segmentApp1(Buffer.concat([Buffer.from("http://ns.adobe.com/xap/1.0/\0", "latin1"), Buffer.from(paquetXmp(infos), "utf8")]));
  const ajouts = exifPresent ? [xmp] : [segmentApp1(blocExif(infos)), xmp];
  return Buffer.concat([octets.subarray(0, pos), ...ajouts, octets.subarray(pos)]);
}

// ─── WebP ───────────────────────────────────────────────────────────────────────

type BlocRiff = { type: string; donnees: Buffer };

function lireBlocsRiff(octets: Buffer): BlocRiff[] {
  const blocs: BlocRiff[] = [];
  let pos = 12;
  while (pos + 8 <= octets.length) {
    const type = octets.toString("latin1", pos, pos + 4);
    const taille = octets.readUInt32LE(pos + 4);
    if (pos + 8 + taille > octets.length) throw new Error("WebP tronqué");
    blocs.push({ type, donnees: octets.subarray(pos + 8, pos + 8 + taille) });
    pos += 8 + taille + (taille % 2);
  }
  return blocs;
}

function ecrireBlocRiff(b: BlocRiff): Buffer {
  const entete = Buffer.alloc(8);
  entete.write(b.type, 0, "latin1");
  entete.writeUInt32LE(b.donnees.length, 4);
  return Buffer.concat([entete, b.donnees, b.donnees.length % 2 ? Buffer.from([0]) : Buffer.alloc(0)]);
}

// Dimensions et canal alpha d'un WebP simple (VP8 avec perte ou VP8L sans perte).
function dimensionsWebp(b: BlocRiff): { largeur: number; hauteur: number; alpha: boolean } {
  if (b.type === "VP8 ") {
    if (b.donnees.length < 10) throw new Error("bloc VP8 illisible");
    return { largeur: b.donnees.readUInt16LE(6) & 0x3fff, hauteur: b.donnees.readUInt16LE(8) & 0x3fff, alpha: false };
  }
  if (b.type === "VP8L") {
    if (b.donnees.length < 5 || b.donnees[0] !== 0x2f) throw new Error("bloc VP8L illisible");
    const v = b.donnees.readUInt32LE(1);
    return { largeur: (v & 0x3fff) + 1, hauteur: ((v >>> 14) & 0x3fff) + 1, alpha: ((v >>> 28) & 1) === 1 };
  }
  throw new Error(`bloc WebP inattendu : ${b.type}`);
}

function marquerWebp(octets: Buffer, infos: InfosMarquageIa): Buffer {
  let blocs = lireBlocsRiff(octets).filter((b) => b.type !== "XMP ");
  const xmp: BlocRiff = { type: "XMP ", donnees: Buffer.from(paquetXmp(infos), "utf8") };
  if (blocs[0]?.type === "VP8X") {
    const vp8x = Buffer.from(blocs[0].donnees);
    vp8x[0] |= 0x04; // drapeau XMP
    blocs = [{ type: "VP8X", donnees: vp8x }, ...blocs.slice(1)];
  } else {
    // Format simple : il faut un en-tête étendu VP8X pour porter des métadonnées.
    const image = blocs.find((b) => b.type === "VP8 " || b.type === "VP8L");
    if (!image) throw new Error("WebP sans image");
    const { largeur, hauteur, alpha } = dimensionsWebp(image);
    const vp8x = Buffer.alloc(10);
    vp8x[0] = 0x04 | (alpha ? 0x10 : 0);
    vp8x.writeUIntLE(largeur - 1, 4, 3);
    vp8x.writeUIntLE(hauteur - 1, 7, 3);
    blocs = [{ type: "VP8X", donnees: vp8x }, ...blocs];
  }
  const corps = Buffer.concat([...blocs, xmp].map(ecrireBlocRiff));
  const entete = Buffer.alloc(12);
  entete.write("RIFF", 0, "latin1");
  entete.writeUInt32LE(corps.length + 4, 4);
  entete.write("WEBP", 8, "latin1");
  return Buffer.concat([entete, corps]);
}
