import { describe, it } from "node:test";
import assert from "node:assert/strict";
import sharp from "sharp";
import { DIGITAL_SOURCE_TYPE_IA, formatImage, marquerImageIa } from "./marquage-ia";
import { avecMarquageIa } from "./index";

const INFOS = { fournisseur: "OpenAI", modele: "gpt-image-1", date: new Date("2026-11-23T10:20:30Z") };

const base = (alpha = false) =>
  sharp({ create: { width: 37, height: 21, channels: alpha ? 4 : 3, background: alpha ? { r: 200, g: 40, b: 90, alpha: 0.5 } : { r: 200, g: 40, b: 90 } } });

async function pixels(octets: Buffer) {
  return sharp(octets).raw().toBuffer();
}

async function verifierXmp(octets: Buffer) {
  const meta = await sharp(octets).metadata();
  assert.ok(meta.xmp, "XMP absent");
  const xmp = meta.xmp!.toString("utf8");
  assert.ok(xmp.includes(DIGITAL_SOURCE_TYPE_IA));
  assert.ok(xmp.includes('xmp:CreatorTool="OpenAI gpt-image-1"'));
  assert.ok(xmp.includes('xmp:CreateDate="2026-11-23T10:20:30.000Z"'));
  assert.ok(xmp.includes("Generated by AI"));
  return meta;
}

describe("marquage IA des images — PNG", () => {
  it("ajoute les blocs texte et le XMP sans toucher aux pixels", async () => {
    const png = await base().png().toBuffer();
    const marque = marquerImageIa(png, INFOS);
    assert.equal(formatImage(marque), "png");
    const meta = await verifierXmp(marque);
    const textes = Object.fromEntries((meta.comments ?? []).map((c) => [c.keyword, c.text]));
    assert.equal(textes["AI-Generated"], "true");
    assert.equal(textes["Software"], "OpenAI gpt-image-1");
    assert.equal(textes["Creation Time"], "2026-11-23T10:20:30.000Z");
    assert.deepEqual(await pixels(marque), await pixels(png));
  });
});

describe("marquage IA des images — JPEG", () => {
  it("ajoute un EXIF et un XMP sans réencoder", async () => {
    const jpeg = await base().jpeg({ quality: 80 }).toBuffer();
    const marque = marquerImageIa(jpeg, INFOS);
    assert.equal(formatImage(marque), "jpeg");
    const meta = await verifierXmp(marque);
    assert.ok(meta.exif, "EXIF absent");
    const exif = meta.exif!.toString("latin1");
    assert.ok(exif.includes("Generated by AI (OpenAI gpt-image-1)"));
    assert.ok(exif.includes("2026:11:23 10:20:30"));
    assert.deepEqual(await pixels(marque), await pixels(jpeg));
  });

  it("garde un EXIF existant et n'ajoute que le XMP", async () => {
    const jpeg = await base().jpeg().withExif({ IFD0: { Copyright: "Boutique" } }).toBuffer();
    const marque = marquerImageIa(jpeg, INFOS);
    const meta = await verifierXmp(marque);
    assert.ok(meta.exif!.toString("latin1").includes("Boutique"));
  });
});

describe("marquage IA des images — WebP", () => {
  for (const [nom, encoder] of [
    ["avec perte (VP8)", () => base().webp({ quality: 80 })],
    ["sans perte (VP8L) avec alpha", () => base(true).webp({ lossless: true })],
  ] as const) {
    it(`ajoute le XMP — ${nom}`, async () => {
      const webp = await encoder().toBuffer();
      const marque = marquerImageIa(webp, INFOS);
      assert.equal(formatImage(marque), "webp");
      const meta = await verifierXmp(marque);
      assert.equal(meta.width, 37);
      assert.equal(meta.height, 21);
      assert.deepEqual(await pixels(marque), await pixels(webp));
    });
  }

  it("WebP déjà étendu (VP8X) : drapeau XMP posé", async () => {
    const webp = await base(true).webp({ quality: 70 }).withExif({ IFD0: { Copyright: "x" } }).toBuffer();
    const marque = marquerImageIa(webp, INFOS);
    await verifierXmp(marque);
    assert.ok(marque[20] & 0x04);
  });
});

describe("marquage IA à la génération", () => {
  it("l'image renvoyée par generateImage porte les métadonnées", async () => {
    const png = await base().png().toBuffer();
    const image = avecMarquageIa(
      { base64: png.toString("base64"), mimeType: "image/png", model: "gpt-image-1", tokensEntree: 0, tokensSortie: 0, coutUsd: null },
      "OpenAI",
      INFOS.date
    );
    await verifierXmp(Buffer.from(image.base64, "base64"));
    assert.equal(image.mimeType, "image/png");
  });

  it("fichier non reconnu : renvoyé tel quel, sans erreur", () => {
    const image = { base64: Buffer.from("pas une image").toString("base64"), mimeType: "image/png", model: "m", tokensEntree: 0, tokensSortie: 0, coutUsd: null };
    const erreur = console.error;
    console.error = () => {};
    try {
      assert.equal(avecMarquageIa(image, "OpenAI").base64, image.base64);
    } finally {
      console.error = erreur;
    }
  });
});
